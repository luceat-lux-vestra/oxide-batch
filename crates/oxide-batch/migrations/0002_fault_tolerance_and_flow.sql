CREATE TABLE ob_flow_decision (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    job_execution_id bigint NOT NULL
        REFERENCES ob_job_execution (id) ON DELETE RESTRICT,
    source_step_execution_id bigint
        REFERENCES ob_step_execution (id) ON DELETE RESTRICT,
    reused_decision_id bigint
        REFERENCES ob_flow_decision (id) ON DELETE RESTRICT,
    sequence bigint NOT NULL CHECK (sequence > 0),
    source_node_id varchar(128) COLLATE "C" NOT NULL
        CHECK (octet_length(source_node_id) BETWEEN 1 AND 128),
    observed_outcome varchar(64) COLLATE "C" NOT NULL
        CHECK (octet_length(observed_outcome) BETWEEN 1 AND 64),
    target_node_id varchar(128) COLLATE "C"
        CHECK (octet_length(target_node_id) BETWEEN 1 AND 128),
    transition_kind varchar(32) COLLATE "C" NOT NULL
        CHECK (transition_kind IN (
            'STEP_EXIT', 'DECIDER', 'COMPLETED_STEP_REUSE'
        )),
    terminal_kind varchar(16) COLLATE "C"
        CHECK (terminal_kind IN ('COMPLETE', 'FAIL', 'STOP')),
    plan_fingerprint bytea NOT NULL CHECK (octet_length(plan_fingerprint) = 32),
    input_digest bytea NOT NULL CHECK (octet_length(input_digest) = 32),
    decided_at timestamptz NOT NULL,
    CONSTRAINT ob_flow_decision_sequence_unique
        UNIQUE (job_execution_id, sequence),
    CONSTRAINT ob_flow_decision_source_unique
        UNIQUE (job_execution_id, source_node_id),
    CONSTRAINT ob_flow_decision_target_shape
        CHECK (
            (target_node_id IS NOT NULL AND terminal_kind IS NULL)
            OR (target_node_id IS NULL AND terminal_kind IS NOT NULL)
        )
);

