-- Schema 1 declared the category list as an unnamed column check. The
-- generated name is dropped by definition rather than by assumed spelling so
-- the replacement list is the only remaining category constraint.
DO $$
DECLARE
    target regclass;
    generated text;
BEGIN
    FOREACH target IN ARRAY ARRAY[
        'oxide_batch.ob_job_execution'::regclass,
        'oxide_batch.ob_step_execution'::regclass
    ] LOOP
        FOR generated IN
            SELECT conname FROM pg_catalog.pg_constraint
            WHERE conrelid = target
              AND contype = 'c'
              AND pg_get_constraintdef(oid) LIKE '%INVALID_DEFINITION%'
        LOOP
            EXECUTE format(
                'ALTER TABLE %s DROP CONSTRAINT %I', target::text, generated
            );
        END LOOP;
    END LOOP;
END
$$;

